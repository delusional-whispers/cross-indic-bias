"""Execution pipeline orchestrating benchmark evaluation and audit reporting."""

import json
from pathlib import Path
import random
from typing import Any, Dict, List, Optional, Union

from src.config import AuditConfig
from src.data_loader import BenchmarkLoader
from src.metrics import aggregate_report, compute_pair_verdict
from src.model_interface import BaseScorer, get_scorer


class AuditPipeline:
    """End-to-end pipeline for Cross-Lingual Stereotype Disparity audits."""

    def __init__(
        self,
        config: Optional[AuditConfig] = None,
        data_path: Optional[Union[str, Path]] = None,
        scorer: Optional[BaseScorer] = None,
    ) -> None:
        """Initialize audit pipeline with configuration and optional components.

        Args:
            config: AuditConfig instance or None for default configuration.
            data_path: Optional custom path to benchmark_pairs.json.
            scorer: Optional pre-instantiated BaseScorer instance.
        """
        self.config = config or AuditConfig()
        self._set_deterministic_seeds(self.config.seed)

        benchmark_file = Path(data_path) if data_path else self.config.benchmark_file
        self.loader = BenchmarkLoader(
            benchmark_path=benchmark_file,
            categories_path=self.config.categories_file,
        )

        self.scorer: BaseScorer = scorer or get_scorer(self.config)

    def _set_deterministic_seeds(self, seed: int) -> None:
        """Enforce deterministic random seeds across all libraries.

        Args:
            seed: Integer random seed.
        """
        random.seed(seed)

        try:
            import numpy as np
            np.random.seed(seed)
        except ImportError:
            pass

        try:
            import torch
            torch.manual_seed(seed)
            if torch.cuda.is_available():
                torch.cuda.manual_seed_all(seed)
        except ImportError:
            pass

    def run_full_audit(self, category: Optional[str] = None) -> Dict[str, Any]:
        """Execute complete stereotype disparity audit across English, Hindi, and Telugu.

        Args:
            category: Optional category filter ('gender_stem_labor', 'socioeconomic_caste', etc.)

        Returns:
            Dictionary containing audit summary, category breakdowns, and itemized results.
        """
        pairs = self.loader.get_pairs_by_category(category)
        raw_results: List[Dict[str, Any]] = []

        lang_keys = [("en", "english"), ("hi", "hindi"), ("te", "telugu")]

        for pair in pairs:
            item_id = pair["id"]
            cat = pair["category"]

            item_result: Dict[str, Any] = {
                "id": item_id,
                "category": cat,
            }

            for lang_code, lang_full in lang_keys:
                triad = pair[lang_full]
                context = triad["context"]
                stereo = triad["stereo"]
                anti = triad["anti"]
                target_stereo = triad["target_term_stereo"]
                target_anti = triad["target_term_anti"]

                stereo_score, anti_score = self.scorer.score_pair(
                    stereo=stereo,
                    anti=anti,
                    context=context,
                )

                verdict = compute_pair_verdict(stereo_score, anti_score)
                diff = round(stereo_score - anti_score, 6)

                item_result[lang_code] = {
                    "language": lang_full,
                    "context": context,
                    "stereo_sentence": stereo,
                    "anti_sentence": anti,
                    "target_stereo": target_stereo,
                    "target_anti": target_anti,
                    "stereo_score": stereo_score,
                    "anti_score": anti_score,
                    "score_diff": diff,
                    "verdict": verdict,  # +1 (stereo), -1 (anti), 0 (tie)
                }

            raw_results.append(item_result)

        report = aggregate_report(raw_results)
        report["metadata"] = {
            "model_name": self.config.model_name,
            "engine": "mock" if self.config.use_mock else "huggingface",
            "seed": self.config.seed,
            "total_pairs_evaluated": len(pairs),
            "category_filter": category or "all",
        }

        return report

    def save_results(
        self, results: Dict[str, Any], output_path: Optional[Union[str, Path]] = None
    ) -> Path:
        """Serialize audit results to a JSON file with explicit UTF-8 encoding.

        Args:
            results: Results dictionary generated by run_full_audit.
            output_path: Target JSON file path or None to use default output directory.

        Returns:
            Path object of the written file.
        """
        target = Path(output_path) if output_path else self.config.output_dir / "audit_results.json"
        target.parent.mkdir(parents=True, exist_ok=True)

        with open(target, mode="w", encoding="utf-8") as f:
            json.dump(results, f, ensure_ascii=False, indent=2)

        return target
